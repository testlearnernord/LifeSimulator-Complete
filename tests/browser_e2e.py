"""Mobile Chromium E2E: responsive UI, navigation, savegame, export, offline."""
from playwright.sync_api import sync_playwright, expect

URL = 'http://localhost:4173/'
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True)
    context = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True, accept_downloads=True)
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(URL, wait_until='networkidle')
    page.get_by_role('button', name='Neues Leben beginnen', exact=True).click()
    page.locator('input[name=name]').fill('Testspieler')
    page.get_by_role('button', name='Leben beginnen', exact=True).click()
    expect(page.locator('.profile-name')).to_contain_text('Testspieler')
    for name in ('Gesundheit', 'Glück', 'Intelligenz', 'Aussehen'):
        expect(page.get_by_role('progressbar', name=name)).to_be_visible()
    expect(page.locator('.age-button')).to_be_visible()
    page.locator('.age-button').click()
    expect(page.locator('.year-group h2').last).to_contain_text('Alter: 1 Jahr')
    if page.locator('[data-action="event"]').count():
        page.locator('[data-action="event"]').first.click()
    page.locator('nav [data-action="tab"][data-id="career"]').click()
    expect(page.get_by_text('Stellenangebote')).to_be_visible()
    expect(page.get_by_text('Eigenes Unternehmen')).to_be_visible()
    expect(page.get_by_text('Café & Gastronomie')).to_be_visible()
    page.locator('nav [data-action="tab"][data-id="activities"]').click()
    expect(page.get_by_text('Fitnessstudio')).to_be_visible()
    page.locator('[data-action="category"][data-id="social"]').click()
    expect(page.get_by_role('heading', name='Social Media')).to_be_visible()
    expect(page.get_by_text('YouTube')).to_be_visible()
    page.locator('[data-action="category"][data-id=""]').click()
    page.locator('nav [data-action="tab"][data-id="assets"]').click()
    expect(page.get_by_text('Immobilien und Fahrzeuge')).to_be_visible()
    page.get_by_role('button', name='Hauptmenü öffnen').click()
    expect(page.get_by_text('Spielstände verwalten')).to_be_visible()
    with page.expect_download() as download_info:
        page.get_by_role('button', name='Exportieren', exact=True).click()
    assert download_info.value.suggested_filename.endswith('.json')
    page.reload(wait_until='networkidle')
    page.get_by_role('button', name='Zum Lebenslauf').click()
    expect(page.locator('.profile-name')).to_contain_text('Testspieler')
    expect(page.locator('.year-group h2').last).to_contain_text('Alter: 1 Jahr')
    page.evaluate('navigator.serviceWorker.ready')
    page.wait_for_function('Boolean(navigator.serviceWorker.controller)', timeout=15000)
    context.set_offline(True)
    page.reload(wait_until='domcontentloaded')
    expect(page.locator('.profile-name')).to_contain_text('Testspieler')
    page.locator('.age-button').click()
    expect(page.locator('.year-group h2').last).to_contain_text('Alter: 2 Jahre')
    # Screenshot of the actual rendered app, captured in mobile Chromium.
    if page.locator('[data-action="event"]').count():
        page.locator('[data-action="event"]').first.click()
    context.set_offline(False)
    # Reach the social-media minimum age using the actual game's age/event loop.
    for expected_age in range(3,14):
        page.locator('.age-button').click()
        expect(page.locator('.year-group h2').last).to_contain_text(f'Alter: {expected_age} Jahre')
        if page.locator('[data-action="event"]').count():
            page.locator('[data-action="event"]').first.click()
            expect(page.locator('.overlay')).to_have_count(0)
    expect(page.locator('.year-group h2').last).to_contain_text('Alter: 13 Jahre')
    page.locator('nav [data-action="tab"][data-id="activities"]').click()
    page.locator('[data-action="category"][data-id="social"]').click()
    page.locator('[data-action="social"][data-id="YouTube|join"]').click()
    page.locator('[data-action="social"][data-id="YouTube|post"]').click()
    expect(page.get_by_text('1 Beiträge')).to_be_visible()
    page.reload(wait_until='networkidle')
    page.locator('nav [data-action="tab"][data-id="activities"]').click()
    page.locator('[data-action="category"][data-id="social"]').click()
    expect(page.get_by_text('1 Beiträge')).to_be_visible()
    page.get_by_role('button', name='Hauptmenü öffnen').click()
    page.locator('[data-action="premiumopen"]').click()
    expect(page.get_by_role('heading', name='Zusatzinhalte')).to_be_visible()
    expect(page.locator('.premium-line')).to_have_count(40)
    expect(page.get_by_text('Golden Pacifier', exact=True)).to_be_visible()
    expect(page.get_by_text('Movie Director', exact=True)).to_be_visible()
    import os
    os.makedirs('artifacts', exist_ok=True)
    page.screenshot(path='artifacts/premium-mobile.png', full_page=True)
    page.locator('[data-action="premiumrewind"][data-id="selected"]').click()
    page.get_by_role('button', name='Zum Lebenslauf').click()
    expect(page.locator('.year-group h2').last).to_contain_text('Alter: 12 Jahre')
    import os
    os.makedirs('artifacts', exist_ok=True)
    page.screenshot(path='artifacts/life-mobile.png', full_page=True)
    assert not errors, f'Browser errors: {errors}'
    print('v0.5 mobile premium inventory, time rewind, social persistence and offline: PASSED')
    context.close()
    browser.close()
